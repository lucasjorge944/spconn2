-- ADMSPCE16.VW_DESPESA_ATUALIZAR_VALOR source

CREATE FORCE VIEW ADMSPCE16.VW_DESPESA_ATUALIZAR_VALOR(VR_TOTAL_BENS, SQ_DESPESA) AS
SELECT
    SUM(QT_BEM_SERVICO * VR_UNITARIO) AS VR_TOTAL_BENS,
    BS.SQ_DESPESA
FROM ADMSPCE16.VW_EPC_BEM_SERVICO_IMOBILIZADO BS
WHERE (SQ_DESPESA IS NOT NULL)
    AND (BS.SQ_BEM_SERVICO_IMOBILIZADO IS NOT NULL)
GROUP BY BS.SQ_DESPESA;


-- ADMSPCE16.VW_EPC_BEM_SERVICO_IMOBILIZADO source

CREATE FORCE VIEW ADMSPCE16.VW_EPC_BEM_SERVICO_IMOBILIZADO(SQ_BEM_SERVICO, SQ_ENTREGA_PRESTACAO, SQ_RECEITA, SQ_DESPESA, SQ_BEM_SERVICO_IMOBILIZADO, CD_DRD_BEM_SERVICO_RECEITA, CD_DRD_BEM_SERVICO, CD_TIPO_BEM, CD_FONTE_AVALIACAO, DS_FONTE_AVALIACAO_OUTRA, QT_BEM_SERVICO, A, VR_TAXA, VR_TARIFA, NR_LOCALIZADOR, VR_UNITARIO, QT_IMOBILIZADA, VR_UNITARIO_IMOBILIZADO, DS_BEM_SERVICO, ST_INTEGRA_PATRIMONIO, ST_CONJUGE, NR_PLACA_VEICULO, QT_DISPONIVEL, ST_DISPONIVEL, PE_REPRESENTATIVIDADE, VR_TOTAL_FONTE_FP, VR_TOTAL_FONTE_OR, VR_TOTAL_FONTE_FEFC, NR_REGISTRO_CONSELHO) AS
SELECT
    BS.SQ_BEM_SERVICO,
    BS.SQ_ENTREGA_PRESTACAO,
    BS.SQ_RECEITA,
    BS.SQ_DESPESA,
    BS.SQ_BEM_SERVICO_IMOBILIZADO,
    CASE WHEN (BS.SQ_RECEITA IS NULL) THEN BS.CD_DRD_BEM_SERVICO ELSE (SELECT
        RE.CD_DRD
    FROM ADMSPCE16.EPC_RECEITA RE
    WHERE RE.SQ_RECEITA = BS.SQ_RECEITA) END AS CD_DRD_BEM_SERVICO_RECEITA,
    BS.CD_DRD_BEM_SERVICO,
    BS.CD_TIPO_BEM,
    BS.CD_FONTE_AVALIACAO,
    BS.DS_FONTE_AVALIACAO_OUTRA,
    BS.QT_BEM_SERVICO,
    BS.VR_UNITARIO AS A,
    BS.VR_TAXA,
    BS.VR_TARIFA,
    BS.NR_LOCALIZADOR,
    CASEWHEN((BS.SQ_BEM_SERVICO_IMOBILIZADO IS NOT NULL), CASEWHEN((BS.SQ_RECEITA IS NOT NULL), BS.VR_UNITARIO, BSN.VR_UNITARIO), BS.VR_UNITARIO) AS VR_UNITARIO,
    (SELECT
        SUM(BSI.QT_BEM_SERVICO)
    FROM ADMSPCE16.EPC_BEM_SERVICO BSI
    WHERE BSI.SQ_BEM_SERVICO_IMOBILIZADO = BS.SQ_BEM_SERVICO) AS QT_IMOBILIZADA,
    BSN.VR_UNITARIO AS VR_UNITARIO_IMOBILIZADO,
    BS.DS_BEM_SERVICO,
    BS.ST_INTEGRA_PATRIMONIO,
    BS.ST_CONJUGE,
    BS.NR_PLACA_VEICULO,
    (BS.QT_BEM_SERVICO - NVL((SELECT
        SUM(BI2.QT_BEM_SERVICO) AS QT_IMOBILIZADA
    FROM ADMSPCE16.EPC_BEM_SERVICO BI2
    WHERE BI2.SQ_BEM_SERVICO_IMOBILIZADO = BS.SQ_BEM_SERVICO), 0)) AS QT_DISPONIVEL,
    CASE WHEN (BS.QT_BEM_SERVICO <= NVL((SELECT
        SUM(BI2.QT_BEM_SERVICO) AS QT_IMOBILIZADA
    FROM ADMSPCE16.EPC_BEM_SERVICO BI2
    WHERE BI2.SQ_BEM_SERVICO_IMOBILIZADO = BS.SQ_BEM_SERVICO), 0)) THEN 0 ELSE 1 END AS ST_DISPONIVEL,
    CASE WHEN (BS.SQ_RECEITA IS NOT NULL) THEN ROUND((((BS.QT_BEM_SERVICO * BS.VR_UNITARIO) / (SELECT
        RE.VR_LANCAMENTO
    FROM ADMSPCE16.EPC_RECEITA RE
    WHERE RE.SQ_RECEITA = BS.SQ_RECEITA)) * 100), 2) ELSE ROUND((((BS.QT_BEM_SERVICO * BS.VR_UNITARIO) / (SELECT
        DE.VR_LANCAMENTO
    FROM ADMSPCE16.EPC_DESPESA DE
    WHERE DE.SQ_DESPESA = BS.SQ_DESPESA)) * 100), 2) END AS PE_REPRESENTATIVIDADE,
    CASE WHEN (BS.SQ_RECEITA IS NOT NULL) THEN NVL((SELECT
        RE.VR_LANCAMENTO
    FROM ADMSPCE16.EPC_RECEITA RE
    WHERE (RE.TP_FONTE_ORIGEM = '0')
        AND (RE.SQ_RECEITA = BS.SQ_RECEITA)), 0) ELSE NVL((SELECT
        SUM(PD.VR_PARCELAMENTO)
    FROM ADMSPCE16.EPC_PARCELAMENTO PD
    WHERE (PD.TP_FONTE_ORIGEM = '0')
        AND (PD.SQ_DESPESA = BS.SQ_DESPESA)), 0) END AS VR_TOTAL_FONTE_FP,
    CASE WHEN (BS.SQ_RECEITA IS NOT NULL) THEN NVL((SELECT
        RE.VR_LANCAMENTO
    FROM ADMSPCE16.EPC_RECEITA RE
    WHERE (RE.SQ_RECEITA = BS.SQ_RECEITA)
        AND (NVL(RE.TP_FONTE_ORIGEM, '1') = '1')), 0) ELSE NVL((SELECT
        SUM(PD.VR_PARCELAMENTO)
    FROM ADMSPCE16.EPC_PARCELAMENTO PD
    WHERE (PD.TP_FONTE_ORIGEM = '1')
        AND (PD.SQ_DESPESA = BS.SQ_DESPESA)), 0) END AS VR_TOTAL_FONTE_OR,
    CASE WHEN (BS.SQ_RECEITA IS NOT NULL) THEN NVL((SELECT
        RE.VR_LANCAMENTO
    FROM ADMSPCE16.EPC_RECEITA RE
    WHERE (RE.TP_FONTE_ORIGEM = '2')
        AND (RE.SQ_RECEITA = BS.SQ_RECEITA)), 0) ELSE NVL((SELECT
        SUM(PD.VR_PARCELAMENTO)
    FROM ADMSPCE16.EPC_PARCELAMENTO PD
    WHERE (PD.TP_FONTE_ORIGEM = '2')
        AND (PD.SQ_DESPESA = BS.SQ_DESPESA)), 0) END AS VR_TOTAL_FONTE_FEFC,
    BS.NR_REGISTRO_CONSELHO
FROM ADMSPCE16.EPC_BEM_SERVICO BS
LEFT OUTER JOIN ADMSPCE16.EPC_BEM_SERVICO BSN
    ON BSN.SQ_BEM_SERVICO = BS.SQ_BEM_SERVICO_IMOBILIZADO;


-- ADMSPCE16.VW_EPC_SOBRA_NAO_FINANCEIRO_42 source

CREATE FORCE VIEW ADMSPCE16.VW_EPC_SOBRA_NAO_FINANCEIRO_42(SQ_ENTREGA_PRESTACAO, SQ_DESPESA, TP_FONTE_ORIGEM, VALORORIGEN, VR_PARCELAMENTO, VALOR_FEFC, VALOR_FP, VALOR_OR, VALORDOACAO, CODIGODRD, TP_FONTE_ORIGEM2) AS
(SELECT
    D.SQ_ENTREGA_PRESTACAO,
    D.SQ_DESPESA,
    NVL(P.TP_FONTE_ORIGEM, 1) AS TP_FONTE_ORIGEM,
    D2.VR_LANCAMENTO AS VALORORIGEN,
    NVL(P.VR_PARCELAMENTO, 0) AS VR_PARCELAMENTO,
    NVL(DECODE(P.TP_FONTE_ORIGEM, 2, P.VR_PARCELAMENTO), 0) AS VALOR_FEFC,
    NVL(DECODE(P.TP_FONTE_ORIGEM, 0, P.VR_PARCELAMENTO), 0) AS VALOR_FP,
    NVL(DECODE(P.TP_FONTE_ORIGEM, 1, P.VR_PARCELAMENTO), 0) AS VALOR_OR,
    D.VR_LANCAMENTO AS VALORDOACAO,
    DECODE(NVL(P.TP_FONTE_ORIGEM, 1), 0, '300200000', 1, '300200001', 2, '300200002') AS CODIGODRD,
    DECODE(NVL(P.TP_FONTE_ORIGEM, 1), 0, STRINGDECODE('4.2.2 - Doa\u00e7\u00f5es de bens m\u00f3veis ou im\u00f3veis efetuadas a candidatos/comit\u00eas financeiros/partidos - FP'), 1, STRINGDECODE('4.2.3 - Doa\u00e7\u00f5es de bens m\u00f3veis ou im\u00f3veis efetuadas a candidatos/comit\u00eas financeiros/partidos - OR'), 2, STRINGDECODE('4.2.1 - Doa\u00e7\u00f5es de bens m\u00f3veis ou im\u00f3veis efetuadas a candidatos/comit\u00eas financeiros/partidos - FEFC')) AS TP_FONTE_ORIGEM2
FROM ADMSPCE16.EPC_DESPESA D
INNER JOIN ADMSPCE16.EPC_BEM_SERVICO B
    ON 1=1
INNER JOIN ADMSPCE16.EPC_BEM_SERVICO B2
    ON 1=1
INNER JOIN ADMSPCE16.EPC_DESPESA D2
    ON 1=1
INNER JOIN ADMSPCE16.EPC_PARCELAMENTO P
    ON 1=1
WHERE (D.CD_DRD = '30020000')
    AND (((P.SQ_ENTREGA_PRESTACAO = D2.SQ_ENTREGA_PRESTACAO)
    AND (P.SQ_DESPESA = D2.SQ_DESPESA))
    AND (((D2.SQ_ENTREGA_PRESTACAO = B2.SQ_ENTREGA_PRESTACAO)
    AND (D2.SQ_DESPESA = B2.SQ_DESPESA))
    AND (((B2.SQ_ENTREGA_PRESTACAO = B.SQ_ENTREGA_PRESTACAO)
    AND (B2.SQ_BEM_SERVICO = B.SQ_BEM_SERVICO_IMOBILIZADO))
    AND ((B.SQ_ENTREGA_PRESTACAO = D.SQ_ENTREGA_PRESTACAO)
    AND (B.SQ_DESPESA = D.SQ_DESPESA))))))
UNION
(SELECT
    D.SQ_ENTREGA_PRESTACAO,
    D.SQ_DESPESA,
    1 AS TP_FONTE_ORIGEM,
    D2.VR_LANCAMENTO AS VALORORIGEN,
    (D2.VR_LANCAMENTO - NVL(P.VR_PARCELAMENTO, 0)) AS VR_PARCELAMENTO,
    0 AS VALOR_FEFC,
    0 AS VALOR_FP,
    (D2.VR_LANCAMENTO - NVL(P.VR_PARCELAMENTO, 0)) AS VALOR_OR,
    D.VR_LANCAMENTO AS VALORDOACAO,
    '300200001' AS CODIGODRD,
    STRINGDECODE('4.2.3 - Doa\u00e7\u00f5es de bens m\u00f3veis ou im\u00f3veis efetuadas a candidatos/comit\u00eas financeiros/partidos - OR') AS TP_FONTE_ORIGEM2
FROM ADMSPCE16.EPC_DESPESA D
INNER JOIN ADMSPCE16.EPC_BEM_SERVICO B
    ON 1=1
INNER JOIN ADMSPCE16.EPC_BEM_SERVICO B2
    ON 1=1
INNER JOIN ADMSPCE16.EPC_DESPESA D2
    ON 1=1
LEFT OUTER JOIN ADMSPCE16.EPC_PARCELAMENTO P
    ON (P.SQ_ENTREGA_PRESTACAO = D2.SQ_ENTREGA_PRESTACAO)
    AND (P.SQ_DESPESA = D2.SQ_DESPESA)
WHERE ((D.CD_DRD = '30020000')
    AND (((SELECT
    (D3.VR_LANCAMENTO - SUM(NVL(P3.VR_PARCELAMENTO, 0)))
FROM ADMSPCE16.EPC_DESPESA D3
INNER JOIN ADMSPCE16.EPC_PARCELAMENTO P3
    ON 1=1
WHERE ((D3.SQ_ENTREGA_PRESTACAO = D2.SQ_ENTREGA_PRESTACAO)
    AND (D3.SQ_DESPESA = D2.SQ_DESPESA))
    AND ((P3.SQ_ENTREGA_PRESTACAO = D3.SQ_ENTREGA_PRESTACAO)
    AND (P3.SQ_DESPESA = D3.SQ_DESPESA))) > 0)
    OR (P.VR_PARCELAMENTO IS NULL)))
    AND (((D2.SQ_ENTREGA_PRESTACAO = B2.SQ_ENTREGA_PRESTACAO)
    AND (D2.SQ_DESPESA = B2.SQ_DESPESA))
    AND (((B2.SQ_ENTREGA_PRESTACAO = B.SQ_ENTREGA_PRESTACAO)
    AND (B2.SQ_BEM_SERVICO = B.SQ_BEM_SERVICO_IMOBILIZADO))
    AND ((B.SQ_ENTREGA_PRESTACAO = D.SQ_ENTREGA_PRESTACAO)
    AND (B.SQ_DESPESA = D.SQ_DESPESA)))));


-- ADMSPCE16.VW_EPC_SOBRA_NAO_FINANCEIRO_42_PIVOT source

CREATE FORCE VIEW ADMSPCE16.VW_EPC_SOBRA_NAO_FINANCEIRO_42_PIVOT(SQ_ENTREGA_PRESTACAO, SQ_DESPESA, TP_FONTE_ORIGEM, DOACAO_FECF, DOACAO_FP, DOACAO_OR, CODIGODRD, TP_FONTE_ORIGEM2) AS
SELECT
    V.SQ_ENTREGA_PRESTACAO,
    V.SQ_DESPESA,
    V.TP_FONTE_ORIGEM,
    CASE WHEN ((A.VALORDOACAO - A.VALOR_FEFC) < 0) THEN A.VALORDOACAO WHEN ((A.VALORDOACAO - A.VALOR_FEFC) >= 0) THEN A.VALOR_FEFC ELSE 0 END AS DOACAO_FECF,
    CASE WHEN (((A.VALORDOACAO - A.VALOR_FEFC) < 0)
        AND (((A.VALORDOACAO - A.VALOR_FEFC) - A.VALOR_FP) < 0)) THEN 0 WHEN (((A.VALORDOACAO - A.VALOR_FEFC) - A.VALOR_FP) < 0) THEN (A.VALORDOACAO - A.VALOR_FEFC) WHEN (((A.VALORDOACAO - A.VALOR_FEFC) - A.VALOR_FP) >= 0) THEN A.VALOR_FP ELSE 0 END AS DOACAO_FP,
    CASE WHEN (((A.VALORDOACAO - A.VALOR_FEFC) < 0)
        AND ((((A.VALORDOACAO - A.VALOR_FEFC) - A.VALOR_FP) < 0)
        AND ((((A.VALORDOACAO - A.VALOR_OR) - A.VALOR_FEFC) - A.VALOR_FP) < 0))) THEN 0 WHEN ((((A.VALORDOACAO - A.VALOR_FEFC) - A.VALOR_FP) < 0)
        AND ((((A.VALORDOACAO - A.VALOR_OR) - A.VALOR_FEFC) - A.VALOR_FP) < 0)) THEN 0 WHEN ((((A.VALORDOACAO - A.VALOR_OR) - A.VALOR_FEFC) - A.VALOR_FP) < 0) THEN ((A.VALORDOACAO - A.VALOR_FEFC) - A.VALOR_FP) WHEN ((((A.VALORDOACAO - A.VALOR_OR) - A.VALOR_FEFC) - A.VALOR_FP) >= 0) THEN A.VALOR_OR ELSE 10 END AS DOACAO_OR,
    V.CODIGODRD,
    V.TP_FONTE_ORIGEM2
FROM (
    SELECT
        SQ_ENTREGA_PRESTACAO,
        SQ_DESPESA,
        VALORDOACAO,
        SUM(VALOR_FEFC) AS VALOR_FEFC,
        SUM(VALOR_FP) AS VALOR_FP,
        SUM(VALOR_OR) AS VALOR_OR
    FROM ADMSPCE16.VW_EPC_SOBRA_NAO_FINANCEIRO_42
    GROUP BY SQ_DESPESA, VALORDOACAO
) A
INNER JOIN ADMSPCE16.VW_EPC_SOBRA_NAO_FINANCEIRO_42 V
    ON 1=1
WHERE (V.SQ_ENTREGA_PRESTACAO = A.SQ_ENTREGA_PRESTACAO)
    AND (V.SQ_DESPESA = A.SQ_DESPESA)
ORDER BY 2;


-- ADMSPCE16.VW_RECEITA_ATUALIZAR_VALOR source

CREATE FORCE VIEW ADMSPCE16.VW_RECEITA_ATUALIZAR_VALOR(VR_TOTAL_BENS, SQ_RECEITA) AS
SELECT
    SUM(QT_BEM_SERVICO * VR_UNITARIO) AS VR_TOTAL_BENS,
    BS.SQ_RECEITA
FROM ADMSPCE16.VW_EPC_BEM_SERVICO_IMOBILIZADO BS
WHERE (BS.CD_DRD_BEM_SERVICO <> '20280000')
    AND ((SQ_RECEITA IS NOT NULL)
    AND (BS.SQ_BEM_SERVICO_IMOBILIZADO IS NOT NULL))
GROUP BY BS.SQ_RECEITA;
